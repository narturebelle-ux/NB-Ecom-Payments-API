-- Only the tables this API owns. Plans, orders, payments and refunds stay in public, migrated by Care.

-- Append-only audit trail. No update/delete code path is implemented for this table anywhere.
create table audit_events (
    id bigint generated by default as identity,
    occurred_at timestamp(6),
    actor_user_id bigint,
    actor_roles varchar(255),
    action varchar(255) not null,
    subject_type varchar(255),
    subject_id varchar(255),
    reason varchar(255),
    request_id varchar(255),
    metadata_json text,
    primary key (id)
);

-- When a paid plan ends, worked out once at payment. order_id is a plain ID: no links between schemas.
create table plan_validity (
    order_id bigint not null,
    paid_at timestamp(6) not null,
    expires_at timestamp(6) not null,
    primary key (order_id)
);

-- Saved in the same transaction as the change. Delivery isn't built yet (F4-S4, D18).
create table outbox_events (
    id bigint generated by default as identity,
    event_id varchar(255) not null unique,
    event_type varchar(255) not null,
    payload text not null,
    created_at timestamp(6) not null,
    delivered_at timestamp(6),
    primary key (id)
);
